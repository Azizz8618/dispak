/*
 * perso.c -- experimental on-demand linking of PERSO external-symbol stubs.
 *
 * FOREX leaves the catalog word of an external subprogram (ATM, NR) in the
 * transfer area of the task instead of a jump to the module body.  When
 * executed, the right half of that word is decoded as extract code E62 and
 * DISPAK returns E_UNIMP.  The module bodies themselves are loaded by the
 * emulated Monitor-80, and the correct transfer words already exist in the
 * task code (SBATM/SBRND).  This module replaces the catalog stub with the
 * corresponding transfer word at the moment of the trap and re-executes it.
 *
 * Enabled by BESM6_PERSO_LINK=1.  Off by default: normal runs unaffected.
 * This is an experiment for the Glissada-6 project.
 */

#include "defs.h"
#include <stdio.h>
#include <stdlib.h>

/* Catalog stub words (PERSO catalog relocated to zone 3000). */
#define STUB_ATM 0006245664341624400ULL
#define STUB_NR  0006245434160170000ULL

/* Addresses of FOREX-generated transfer words in SBATM and SBRND. */
#define XFER_ATM_ADDR 010144
#define XFER_NR_ADDR  007765

static unsigned long long
get_word(int addr)
{
        uchar *p = core[addr].w_b;
        return ((unsigned long long)p[0] << 40) |
               ((unsigned long long)p[1] << 32) |
               ((unsigned long long)p[2] << 24) |
               ((unsigned long long)p[3] << 16) |
               ((unsigned long long)p[4] << 8) |
               (unsigned long long)p[5];
}

static void
put_word(int addr, unsigned long long w)
{
        uchar *p = core[addr].w_b;
        p[0] = (w >> 40) & 0xff;
        p[1] = (w >> 32) & 0xff;
        p[2] = (w >> 24) & 0xff;
        p[3] = (w >> 16) & 0xff;
        p[4] = (w >> 8) & 0xff;
        p[5] = w & 0xff;
        cflags[addr] &= ~C_UNPACKED;     /* force re-unpack of the new insn */
        convol[addr] &= ~CV_NUMBER;      /* it is an instruction, not data */
}

/*
 * Replace a PERSO catalog stub at ADDR with the transfer word generated by
 * FOREX.  Return 1 if a replacement was made (the caller must re-execute the
 * instruction), 0 otherwise.
 */
int
perso_patch_at(int addr)
{
        unsigned long long w, xfer;
        const char *name;

        if (!getenv("BESM6_PERSO_LINK"))
                return 0;

        w = get_word(addr);
        if (w == STUB_ATM) {
                xfer = get_word(XFER_ATM_ADDR);
                name = "ATM";
        } else if (w == STUB_NR) {
                xfer = get_word(XFER_NR_ADDR);
                name = "NR";
        } else {
                return 0;
        }

        /* Sanity: the transfer word must be a vjm to a loaded module. */
        if (((xfer >> 16) & 0xffffffULL) == 0) {
                fprintf(stderr, "perso_link: no transfer word for %s\n", name);
                return 0;
        }

        put_word(addr, xfer);
        fprintf(stderr, "perso_link: patched %s at %05o: %016llo -> %016llo\n",
                name, addr, w, xfer);
        return 1;
}
